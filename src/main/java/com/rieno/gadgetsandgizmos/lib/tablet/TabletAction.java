package com.rieno.gadgetsandgizmos.lib.tablet;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import net.minecraft.resources.ResourceLocation;

import java.util.Map;

// Identify one app action and carry its immutable arguments
public record TabletAction(ResourceLocation appId, String tabId, String actionId,
                           Map<String, String> arguments) {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the tablet action
    public TabletAction {
        tabId = tabId == null ? "" : tabId.trim();
        actionId = actionId == null ? "" : actionId.trim();
        arguments = arguments == null ? Map.of() : Map.copyOf(arguments);
    }
}
