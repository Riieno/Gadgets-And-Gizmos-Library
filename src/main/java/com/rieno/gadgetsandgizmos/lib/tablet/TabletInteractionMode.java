package com.rieno.gadgetsandgizmos.lib.tablet;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import java.util.Locale;

// Define where a tablet app accepts use interactions
public enum TabletInteractionMode {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Constants
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    STANDARD,
    READER,
    PUSH;

    // Get the id
    public String id() {
        return name().toLowerCase(Locale.ROOT);
    }

    // Create the tablet interaction mode from id
    public static TabletInteractionMode fromId(String id) {
        if (id == null || id.isBlank()) return STANDARD;
        try {
            return valueOf(id.trim().toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException ignored) {
            return STANDARD;
        }
    }
}
