package com.rieno.gadgetsandgizmos.lib.graph;

// Hold the shared graph registries used by controllers and addon integrations
public final class GraphApi {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Constants
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    private static final GraphNodeRegistry NODES = new GraphNodeRegistry();
    private static final GraphRuntimeRegistry RUNTIMES = new GraphRuntimeRegistry();

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the graph API
    private GraphApi() {
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Get the nodes
    public static GraphNodeRegistry nodes() {
        return NODES;
    }

    // Get the runtimes
    public static GraphRuntimeRegistry runtimes() {
        return RUNTIMES;
    }
}
