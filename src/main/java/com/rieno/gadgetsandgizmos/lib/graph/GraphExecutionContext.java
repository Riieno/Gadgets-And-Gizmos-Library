import java.util.Map;
import java.util.Optional;

// Give reusable nodes access to the small amount of state supplied by their graph host
public interface GraphExecutionContext {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                              MAIN
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Update the graph execution context
    long tick();

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Get the state
    GraphValue state(String key);

    // Set the graph execution state
    void state(String key, GraphValue val);

    // Get the service
    default <T> Optional<T> service(GraphServiceKey<T> key) {
        return Optional.empty();
    }

    // Get the services
    @Deprecated(forRemoval = false)
    default Map<String, Object> services() {
        return Map.of();
    }
}
