package com.rieno.gadgetsandgizmos.lib.graph;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import net.minecraft.resources.ResourceLocation;

// Identify one typed service that a graph host may expose to reusable nodes
public record GraphServiceKey<T>(ResourceLocation id, Class<T> type) {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the graph service key
    public GraphServiceKey {
        if (id == null || type == null) {
            throw new IllegalArgumentException("A graph service key requires an id and type");
        }
    }
}
