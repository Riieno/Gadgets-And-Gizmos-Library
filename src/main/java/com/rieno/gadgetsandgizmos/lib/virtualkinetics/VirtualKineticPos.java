package com.rieno.gadgetsandgizmos.lib.virtualkinetics;

/*--------------------------------------------------------##---------------------------------------------------------

=======================================================================================================================
                                                        IMPORTS
=======================================================================================================================

------------------------------------------------------------##-----------------------------------------------------*/

import net.minecraft.core.BlockPos;
import net.minecraft.core.Vec3i;

// Add a stable virtual slot to a real kinetic block position
public class VirtualKineticPos extends BlockPos {
    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                            DEFAULTS
                                                       #################
                                                           Variables
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Virtual slot
    private final int ct$virtualSlot;

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                        PRELOAD / SETUP
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Initialize the virtual kinetic pos
    public VirtualKineticPos(Vec3i blockPos, int virtualSlot) {
        super(blockPos.getX(), blockPos.getY(), blockPos.getZ());
        this.ct$virtualSlot = virtualSlot;
    }

    /*--------------------------------------------------------##---------------------------------------------------------

    =======================================================================================================================
                                                           Functions
    =======================================================================================================================

    ------------------------------------------------------------##-----------------------------------------------------*/

    // Get the virtual slot
    public int ct$getVirtualSlot() {
        return ct$virtualSlot;
    }
}
